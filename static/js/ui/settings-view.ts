    /**
     * Save the current settings from the form to the config manager.
     * Called when the user clicks 'Save' in the settings modal.
     */
    async function saveConfigToServer() {
        await (config.saveFromForm as () => Promise<void> | void)();

        const syncPromises: Promise<unknown>[] = [];

        if (ApiClient.setMatureContent && config.matureContent !== undefined) {
            syncPromises.push(ApiClient.setMatureContent(Boolean(config.matureContent)).catch(err => {
                console.warn('Failed to sync mature content to server:', err);
            }));
        }
        if (ApiClient.setGhostMode && config.ghostMode !== undefined) {
            syncPromises.push(ApiClient.setGhostMode(Boolean(config.ghostMode)).catch(err => {
                console.warn('Failed to sync ghost mode to server:', err);
            }));
        }
        if (ApiClient.setAutoGenerateDescriptions && config.autoGenerateDescriptions !== undefined) {
            syncPromises.push(ApiClient.setAutoGenerateDescriptions(Boolean(config.autoGenerateDescriptions)).catch(err => {
                console.warn('Failed to sync auto-generate descriptions to server:', err);
            }));
        }

        const tptEl = document.getElementById('time-per-tick') as HTMLInputElement | null;
        if (tptEl && tptEl.value) {
            const minutes = parseInt(tptEl.value, 10);
            if (!isNaN(minutes)) {
                syncPromises.push(ApiClient.setTimePerTick(minutes).catch(err => {
                    console.warn('Failed to sync time per tick:', err);
                }));
            }
        }

        const csEl = document.getElementById('clock-start') as HTMLInputElement | null;
        if (csEl && csEl.value) {
            const m = /^(\d{1,2}):(\d{2})$/.exec(csEl.value);
            if (m) {
                const hour = parseInt(m[1], 10);
                const minute = parseInt(m[2], 10);
                syncPromises.push(ApiClient.setClockStart(hour, minute).catch(err => {
                    console.warn('Failed to sync clock start:', err);
                }));
            }
        }

        await Promise.allSettled(syncPromises);
        if ((window as any).worldState?.fetch) {
            (window as any).worldState.fetch();
        }
    }

