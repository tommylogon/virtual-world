    /**
     * Test the Dedicated Memory Worker API connection.
     * Updates button and diagnostic result display with latency and status.
     */
    async function testMemoryConnection() {
        const btn = document.getElementById('test-memory-btn');
        const resultEl = document.getElementById('memory-test-result');
        if (!btn || !resultEl) return;
        btn.classList.add('testing');
        btn.textContent = 'Testing...';
        resultEl.textContent = '';
        try {
            const client = (config as any).getMemoryLLMClient();
            if (!client) throw new Error('No memory client configured');
            const start = Date.now();
            const resp = await client.chat([{ role: 'user', content: 'Say ok' }], { max_tokens: 16, temperature: 0, label: 'settings/test-memory' });
            const elapsed = Date.now() - start;
            if (resp) {
                btn.classList.remove('testing');
                btn.classList.add('success');
                btn.textContent = 'Connected!';
                resultEl.textContent = 'Connected (' + elapsed + 'ms)';
                resultEl.style.color = '#3fb950';
            } else {
                throw new Error('No response from memory worker');
            }
        } catch (err) {
            btn.classList.remove('testing');
            btn.classList.add('error');
            btn.textContent = 'Failed';
            resultEl.textContent = 'Error: ' + (err instanceof Error ? err.message : String(err));
            resultEl.style.color = '#f85149';
        }
        setTimeout(function() {
            btn.classList.remove('success', 'error');
            btn.textContent = 'Test Connection';
            setTimeout(function() { resultEl.textContent = ''; }, 3000);
        }, 3000);
    }

    async function testConnection() {
        const btn = document.getElementById('test-connection-btn');
        const resultEl = document.getElementById('connection-result');
        if (!btn || !resultEl) return;
        btn.classList.add('testing');
        btn.textContent = '⏳ Testing...';
        resultEl.classList.remove('visible', 'success', 'error');
        try {
            var resp = await llmClient.chat([{ role: 'user', content: 'Say "ok"' }], { max_tokens: 16, temperature: 0, label: 'settings/test-connection' });
            if (resp) {
                btn.classList.remove('testing');
                btn.classList.add('success');
                btn.textContent = '✅ Connected!';
                resultEl.textContent = 'Connection successful!';
                resultEl.classList.add('visible', 'success');
            } else {
                throw new Error('No response');
            }
        } catch (err) {
            btn.classList.remove('testing');
            btn.classList.add('error');
            btn.textContent = '❌ Failed';
            resultEl.textContent = 'Error: ' + (err instanceof Error ? err.message : String(err));
            resultEl.classList.add('visible', 'error');
        }
        setTimeout(function() {
            btn.classList.remove('success', 'error');
            btn.textContent = '🔌 Test Connection';
            setTimeout(function() { resultEl.classList.remove('visible'); }, 2000);
        }, 3000);
    }

