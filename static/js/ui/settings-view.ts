    /**
     * Reads all modal settings into a key-value dictionary.
     */
    function readForm(): Record<string, unknown> {
        const modal = document.getElementById('settings-modal');
        const data: Record<string, unknown> = {};
        if (!modal) return data;

        const inputs = modal.querySelectorAll<HTMLInputElement | HTMLSelectElement | HTMLTextAreaElement>('input, select, textarea');
        inputs.forEach(input => {
            const key = input.getAttribute('data-config') || ELEMENT_ID_TO_CONFIG_KEY[input.id];
            if (!key) return;

            if (input instanceof HTMLInputElement && input.type === 'checkbox') {
                data[key] = input.checked;
            } else if (input.type === 'number' || (input instanceof HTMLInputElement && input.type === 'range')) {
                const step = input.getAttribute('step');
                const val = parseFloat(input.value);
                if (!isNaN(val)) {
                    data[key] = (step && step.includes('.')) ? val : parseInt(input.value, 10);
                }
            } else {
                data[key] = input.value.trim();
            }
        });

        if (data.turnOrder && (window as any).VWSimultaneous?.normalizeMode) {
            data.turnOrder = (window as any).VWSimultaneous.normalizeMode(data.turnOrder, (config as any).turnOrder);
            if ((window as any).VWSimultaneous.isSimultaneous(data.turnOrder)) {
                data.turnBased = false;
            }
        }

        return data;
    }

