#!/usr/bin/env python3
"""Give every note a real changelog, built from the task cards that name it.

A card's ``wiki:`` frontmatter is the task -> note edge. This tool reads that
edge across the whole task tree and writes each note a ``## Changelog`` section
between markers, so a reader of `Movement.md` sees what changed, when, and which
task did it — without anyone hand-maintaining a list that rots.

    python tools/page_changelog.py            # report: which notes would change
    python tools/page_changelog.py --write    # apply

The section is machine-owned between ``<!-- changelog:start -->`` and
``<!-- changelog:end -->``, exactly like ``doc_connected``'s ``## Connected``
block. Never hand-edit inside the markers.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VAULT = ROOT / "docs" / "virtualWorld"
TASKS = VAULT / "dev_tasks"
WIKI_RE = re.compile(r'^\s*wiki:\s*"?\[\[([^\]]+)\]\]"?\s*$', re.M)
FILED_RE = re.compile(r"^\*\*Filed:\*\*\s*(\S+)", re.M)
TITLE_RE = re.compile(r"^#\s+(?:task|bug)-(\d+):\s*(.+)$", re.M)
START = "<!-- changelog:start -->"
END = "<!-- changelog:end -->"

# Statuses that read as history rather than as intent. A `todo` card has not
# changed anything yet, so it does not belong in a changelog.
HISTORY = ("inprogress", "review", "done")


def vault_key(target: str) -> str:
    s = target.strip().split("|")[0].strip()
    return s.lower()


def resolve_note(key: str):
    if not key:
        return None
    direct = VAULT / (key + ".md")
    if direct.exists():
        return direct
    base = key.rsplit("/", 1)[-1] + ".md"
    for hit in VAULT.rglob(base):
        return hit
    return None


def read_note(p: Path):
    """The note's text, or None if it is not valid UTF-8.

    The sweep walks the whole vault, and a handful of older notes carry
    Windows-1252 bytes. Skipping them is safe — this tool only ever *adds* a
    marked block, so a note it cannot read is a note it leaves alone.
    """
    try:
        return p.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        print(f"skipped (not UTF-8): {p.relative_to(ROOT).as_posix()}")
        return None


def note_key(p: Path) -> str:
    """A stable dict key for a note path.

    ``resolve_note`` builds its direct candidate from a *lowercased* key, and
    Windows resolves that to the real file, so the returned path string can be
    lowercase while the same file reached by ``rglob`` is real-case. Comparing
    raw strings then misses, and the stale-block sweep silently wipes changelogs
    that are still current. Normalise before using a path as a key.
    """
    return str(p).replace("\\", "/").lower()


def collect() -> dict:
    """note path -> [entry dicts], from every card that names a note."""
    by_note: dict = {}
    for path in sorted(TASKS.rglob("*.md")):
        text = read_note(path)
        if text is None:
            continue
        m = WIKI_RE.search(text)
        if not m:
            continue
        note = resolve_note(vault_key(m.group(1)))
        if note is None:
            continue
        filed = FILED_RE.search(text)
        title = TITLE_RE.search(text)
        status = path.parent.parent.name  # dev_tasks/<status>/<area>/card.md
        if status not in HISTORY:
            continue
        by_note.setdefault(note_key(note), []).append({
            "id": f"task-{title.group(1)}" if title else path.stem,
            # The full file stem: `[[task-791]]` resolves to nothing, because
            # Obsidian resolves a wikilink against a note's *name*, and the
            # card is named `task-791-feature-mechanic-and-system-page-standard`.
            "stem": path.stem,
            "title": (title.group(2).strip() if title else path.stem),
            "filed": filed.group(1) if filed else "",
            "status": status,
        })
    return by_note


def render(entries: list) -> str:
    rows = sorted(entries, key=lambda e: (e["filed"], e["id"]), reverse=True)
    lines = [
        START,
        "## Changelog",
        "",
        "*Generated by `python tools/page_changelog.py` from the task cards "
        "whose `wiki:` points at this note. Never hand-edit inside the markers.*",
        "",
        "| When | Task | Status |",
        "|---|---|---|",
    ]
    for e in rows:
        when = e["filed"] or "—"
        lines.append(f"| {when} | [[{e['stem']}\\|{e['title']}]] | `{e['status']}` |")
    lines.append(END)
    return "\n".join(lines)


def apply_block(text: str, block: str) -> str:
    """Replace the marked block, or insert it before `## Connected` / at the end."""
    if START in text and END in text:
        head = text[: text.index(START)]
        tail = text[text.index(END) + len(END):]
        return head + block + tail
    marker = "<!-- connected:start -->"
    if marker in text:
        i = text.index(marker)
        return text[:i] + block + "\n\n" + text[i:]
    return text.rstrip() + "\n\n" + block + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="apply the changelogs")
    args = ap.parse_args()

    by_note = collect()
    changed = 0
    for note, entries in sorted(by_note.items()):
        p = Path(note)
        text = read_note(p)
        if text is None:
            continue
        block = render(entries)
        new = apply_block(text, block)
        if new == text:
            continue
        changed += 1
        rel = p.relative_to(ROOT).as_posix()
        if args.write:
            p.write_text(new, encoding="utf-8")
            print(f"updated {rel} ({len(entries)} entr{'y' if len(entries) == 1 else 'ies'})")
        else:
            print(f"would update {rel} ({len(entries)} entries)")

    # A note whose cards all left HISTORY (or were retargeted) keeps a stale
    # block forever unless it is swept here.
    for p in sorted(VAULT.rglob("*.md")):
        if note_key(p) in by_note:
            continue
        text = read_note(p)
        if text is None or START not in text or END not in text:
            continue
        new = text[: text.index(START)] + text[text.index(END) + len(END):]
        new = re.sub(r"\n{3,}", "\n\n", new).rstrip() + "\n"
        if new == text:
            continue
        changed += 1
        rel = p.relative_to(ROOT).as_posix()
        if args.write:
            p.write_text(new, encoding="utf-8")
            print(f"cleared stale changelog from {rel}")
        else:
            print(f"would clear stale changelog from {rel}")

    print(f"\n{len(by_note)} note(s) carry a changelog, {changed} changed.")
    if not args.write:
        print("dry run — pass --write to apply.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
