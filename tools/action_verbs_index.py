#!/usr/bin/env python3
"""Generate (and guard) the client-side action-verbs registry.

`engine/action_verbs.py` declares every verb the simulation and user surfaces
accept, its aliases, scope, target schema, cost tier, mature gate, and bracket
order. This script generates `static/js/agent/action-verbs.generated.js`
(`window.ActionVerbs`) so the browser normalizer, bracket builder, and prompt
prose read the single source of truth without duplication or manual drift.

Usage:
    python tools/action_verbs_index.py --write    # regenerate the JS file
    python tools/action_verbs_index.py --check    # fail on drift
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import engine.action_verbs as action_verbs

OUT_PATH = ROOT / "static" / "js" / "agent" / "action-verbs.generated.js"


def build_js() -> str:
    valid_verbs = sorted([s.id for s in action_verbs.VERBS if not s.mature_gate] +
                         [a for s in action_verbs.VERBS if not s.mature_gate for a in s.aliases])
    mature_verbs = sorted(action_verbs.mature_verbs())
    all_verbs_list = sorted(action_verbs.all_verbs())
    bracket_order_list = list(action_verbs.bracket_order())

    specs_dict = {}
    for s in action_verbs.VERBS:
        spec_data = {
            "id": s.id,
            "aliases": list(s.aliases),
            "scope": s.scope,
            "target_schema": s.target_schema,
            "cost_key": s.cost_key,
            "mature_gate": s.mature_gate,
            "bracket_order": s.bracket_order,
        }
        specs_dict[s.id] = spec_data
        for alias in s.aliases:
            specs_dict[alias] = spec_data

    valid_json = json.dumps(valid_verbs, indent=4)
    mature_json = json.dumps(mature_verbs, indent=4)
    all_json = json.dumps(all_verbs_list, indent=4)
    bracket_json = json.dumps(bracket_order_list, indent=4)
    specs_json = json.dumps(specs_dict, indent=4)

    return f"""/**
 * action-verbs.generated.js - client-side scoped action verbs registry (task-491).
 *
 * GENERATED by tools/action_verbs_index.py --write. DO NOT EDIT BY HAND.
 * Single source of truth: engine/action_verbs.py; `tools/action_verbs_index.py
 * --check` fails when this file drifts from it.
 *
 * @module agent/action-verbs - client mirror of the engine's scoped action verb registry
 * @contributes ActionVerbs: VALID_VERBS, MATURE_VERBS, ALL_VERBS, BRACKET_ORDER, VERB_SPECS, allVerbs, isValidVerb, verbsForScope, bracketOrder
 * @powers Use / use on - single source of truth for action verbs across client and engine
 * @relates engine/action_verbs.py, static/js/agent/action-normalizer.ts, static/js/agent/prompt-builder/contextual-actions.ts
 * @docs docs/virtualWorld/AI & Narration/Agent Engine.md
 */

(function () {{
    'use strict';

    const VALID_VERBS = {valid_json};

    const MATURE_VERBS = {mature_json};

    const ALL_VERBS = {all_json};

    const BRACKET_ORDER = {bracket_json};

    const VERB_SPECS = {specs_json};

    const VALID_SET = new Set(VALID_VERBS);
    const MATURE_SET = new Set(MATURE_VERBS);
    const ALL_SET = new Set(ALL_VERBS);

    function allVerbs(matureEnabled) {{
        return matureEnabled ? ALL_SET : VALID_SET;
    }}

    function isValidVerb(verb, matureEnabled) {{
        if (!verb || typeof verb !== 'string') return false;
        const v = verb.trim().toLowerCase();
        return matureEnabled ? ALL_SET.has(v) : VALID_SET.has(v);
    }}

    function getVerbSpec(verb) {{
        if (!verb || typeof verb !== 'string') return null;
        return VERB_SPECS[verb.trim().toLowerCase()] || null;
    }}

    function bracketOrder() {{
        return [...BRACKET_ORDER];
    }}

    function verbsForScope(scopeName) {{
        if (!scopeName) return [];
        const target = scopeName.toLowerCase().trim();
        const seen = new Set();
        const out = [];
        for (const spec of Object.values(VERB_SPECS)) {{
            if (seen.has(spec.id)) continue;
            seen.add(spec.id);
            const scopes = (spec.scope || '').toLowerCase().split(',').map(s => s.trim());
            if (scopes.includes(target)) {{
                out.push(spec);
            }}
        }}
        return out;
    }}

    const ActionVerbs = {{
        VALID_VERBS,
        MATURE_VERBS,
        ALL_VERBS,
        BRACKET_ORDER,
        VERB_SPECS,
        VALID_SET,
        MATURE_SET,
        ALL_SET,
        allVerbs,
        isValidVerb,
        getVerbSpec,
        bracketOrder,
        verbsForScope
    }};

    if (typeof window !== 'undefined') {{
        window.ActionVerbs = ActionVerbs;
    }}
    if (typeof module !== 'undefined' && module.exports) {{
        module.exports = ActionVerbs;
    }}
}})();
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write generated file")
    parser.add_argument("--check", action="store_true", help="fail on drift")
    args = parser.parse_args()

    content = build_js()

    if args.write:
        OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUT_PATH.write_text(content, encoding="utf-8")
        print(f"Wrote {OUT_PATH.relative_to(ROOT)} ({len(content)} bytes)")
        return 0

    if args.check:
        if not OUT_PATH.exists():
            sys.stderr.write(f"FAIL: {OUT_PATH.relative_to(ROOT)} does not exist. Run with --write.\n")
            return 1
        existing = OUT_PATH.read_text(encoding="utf-8")
        # Normalize newlines for cross-platform comparison
        if existing.replace("\r\n", "\n") != content.replace("\r\n", "\n"):
            sys.stderr.write(f"FAIL: {OUT_PATH.relative_to(ROOT)} is out of sync with engine/action_verbs.py. Run tools/action_verbs_index.py --write.\n")
            return 1
        print("OK: action-verbs.generated.js is up to date.")
        return 0

    parser.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
