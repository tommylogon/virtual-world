'use strict';

// Evaluate CONFIG_SCHEMA from config.js without creating a ConfigManager instance
if (typeof CONFIG_SCHEMA === 'undefined') {
    const src = __readFile('static/js/config.js');
    const endIdx = src.indexOf('class ConfigManagerImpl');
    const schemaSrc = endIdx !== -1 ? src.slice(0, endIdx) : src;
    eval(schemaSrc);
}

const SV = window.SettingsView;

test('CONFIG_SCHEMA defines canonical defaults accessible to benchmark and settings', () => {
    const schema = window.CONFIG_SCHEMA;
    assertTrue(schema !== undefined, 'CONFIG_SCHEMA is exposed globally');
    assertEq(schema.apiBase.default, 'http://localhost:1234/v1', 'default apiBase');
    assertEq(schema.matureContent.type, 'boolean', 'matureContent type');
    assertEq(schema.graphGravitationalConstant.default, -8, 'graphGravitationalConstant default');
});

test('SettingsView.populateForm populates inputs declaratively from config and schema', () => {
    const origDoc = window.document;
    const origConfig = window.config;
    const origWorldState = window.worldState;

    // Mock elements
    const elements = new Map();
    function createMockInput(id, tag = 'input', type = 'text', dataConfig = null, step = null) {
        const el = {
            id,
            tagName: tag.toUpperCase(),
            type,
            value: '',
            checked: false,
            textContent: '',
            getAttribute(attr) {
                if (attr === 'data-config') return dataConfig;
                if (attr === 'step') return step;
                return null;
            }
        };
        elements.set(id, el);
        return el;
    }

    const modalInputs = [
        createMockInput('api-base-input', 'input', 'text', 'apiBase'),
        createMockInput('agent-temperature', 'input', 'range', 'temperature', '0.05'),
        createMockInput('graph-repulsion', 'input', 'range', 'graphGravitationalConstant', '5'),
        createMockInput('agent-mature-content', 'input', 'checkbox', 'matureContent'),
        createMockInput('agent-ghost-mode', 'input', 'checkbox', 'ghostMode')
    ];

    // Companion -val spans
    const tempVal = createMockInput('agent-temperature-val', 'span');
    const grVal = createMockInput('graph-repulsion-val', 'span');

    const modalEl = {
        id: 'settings-modal',
        querySelectorAll(selector) {
            if (selector.includes('input')) return modalInputs;
            return [];
        }
    };
    elements.set('settings-modal', modalEl);

    window.document = {
        getElementById(id) { return elements.get(id) || null; },
        querySelectorAll() { return []; }
    };

    window.config = {
        apiBase: 'http://custom-host:8000/v1',
        temperature: '1.25',
        graphGravitationalConstant: -35,
        matureContent: false,
        ghostMode: false
    };

    window.worldState = {
        data: {
            mature_content: true,
            ghost_mode: true
        }
    };

    try {
        SV.populateForm();

        // 1. Text input populated from config
        assertEq(elements.get('api-base-input').value, 'http://custom-host:8000/v1', 'apiBase populated');

        // 2. Range input and companion span formatted with decimal precision
        assertEq(elements.get('agent-temperature').value, '1.25', 'temperature value');
        assertEq(tempVal.textContent, '1.25', 'temperature -val span formatted');

        // 3. Integer range input
        assertEq(elements.get('graph-repulsion').value, '-35', 'graph repulsion value');
        assertEq(grVal.textContent, '-35', 'graph repulsion -val span');

        // 4. Scenario flags synced from worldState.data
        assertEq(elements.get('agent-mature-content').checked, true, 'matureContent synced from worldState');
        assertEq(elements.get('agent-ghost-mode').checked, true, 'ghostMode synced from worldState');
    } finally {
        window.document = origDoc;
        window.config = origConfig;
        window.worldState = origWorldState;
    }
});

test('SettingsView.saveConfigToServer syncs scenario flags to ApiClient endpoints', async () => {
    const origConfig = window.config;
    const origApiClient = window.ApiClient;

    let savedFromForm = false;
    let matureContentSent = null;
    let ghostModeSent = null;
    let autoDescSent = null;

    window.config = {
        matureContent: true,
        ghostMode: false,
        autoGenerateDescriptions: true,
        saveFromForm: async () => { savedFromForm = true; }
    };

    window.ApiClient = {
        setMatureContent: async (val) => { matureContentSent = val; return { status: 'success' }; },
        setGhostMode: async (val) => { ghostModeSent = val; return { status: 'success' }; },
        setAutoGenerateDescriptions: async (val) => { autoDescSent = val; return { status: 'success' }; }
    };

    try {
        await SV.saveConfigToServer();
        assertTrue(savedFromForm, 'config.saveFromForm was called');
        assertEq(matureContentSent, true, 'ApiClient.setMatureContent received true');
        assertEq(ghostModeSent, false, 'ApiClient.setGhostMode received false');
        assertEq(autoDescSent, true, 'ApiClient.setAutoGenerateDescriptions received true');
    } finally {
        window.config = origConfig;
        window.ApiClient = origApiClient;
    }
});
