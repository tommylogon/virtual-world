#!/usr/bin/env python3
"""Generate (and guard) the client-side actions registry (task-491, task-988).

`engine/actions.py` declares every action the simulation and user surfaces
accept, its aliases, scope, target schema, cost tier, mature gate, and bracket
order. This script generates `static/js/agent/actions.generated.js`
(`window.Actions`) so the browser normalizer, bracket builder, and prompt
prose read the single source of truth without duplication or manual drift.

Usage:
    python tools/actions_index.py --write    # regenerate the JS file
    python tools/actions_index.py --check    # fail on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import engine.actions as actions

OUT_PATH = ROOT / "static" / "js" / "agent" / "actions.generated.js"


def build_js() -> str:
    valid_actions = sorted([s.id for s in actions.ACTIONS if not s.mature_gate] +
                           [a for s in actions.ACTIONS if not s.mature_gate for a in s.aliases])
    mature_actions = sorted(actions.mature_actions())
    all_actions_list = sorted(actions.all_actions())
    bracket_order_list = list(actions.bracket_order())

    specs_dict = {}
    for s in actions.ACTIONS:
        spec_data = {
            "id": s.id,
            "aliases": list(s.aliases),
            "scope": s.scope,
            "target_schema": s.target_schema,
            "cost_key": s.cost_key,
            "mature_gate": s.mature_gate,
            "bracket_order": s.bracket_order,
        }
        specs_dict[s.id] = spec_data
        for alias in s.aliases:
            specs_dict[alias] = spec_data

    valid_json = json.dumps(valid_actions, indent=4)
    mature_json = json.dumps(mature_actions, indent=4)
    all_json = json.dumps(all_actions_list, indent=4)
    bracket_json = json.dumps(bracket_order_list, indent=4)
    specs_json = json.dumps(specs_dict, indent=4)

    return f"""/**
 * actions.generated.js - client-side scoped actions registry (task-491, task-988).
 *
 * GENERATED by tools/actions_index.py --write. DO NOT EDIT BY HAND.
 * Single source of truth: engine/actions.py; `tools/actions_index.py
 * --check` fails when this file drifts from it.
 *
 * @module agent/actions - client mirror of the engine's scoped action registry
 * @contributes Actions: VALID_ACTIONS, MATURE_ACTIONS, ALL_ACTIONS, BRACKET_ORDER, ACTION_SPECS, allActions, isValidAction, actionsForScope, bracketOrder, costOf
 * @powers Use / use on - single source of truth for actions across client and engine
 * @relates engine/actions.py, static/js/agent/action-normalizer.ts, static/js/agent/prompt-builder/contextual-actions.ts
 * @docs docs/virtualWorld/AI & Narration/Agent Engine.md
 */

(function () {{
    'use strict';

    const VALID_ACTIONS = {valid_json};

    const MATURE_ACTIONS = {mature_json};

    const ALL_ACTIONS = {all_json};

    const BRACKET_ORDER = {bracket_json};

    const ACTION_SPECS = {specs_json};

    const VALID_SET = new Set(VALID_ACTIONS);
    const MATURE_SET = new Set(MATURE_ACTIONS);
    const ALL_SET = new Set(ALL_ACTIONS);

    function allActions(matureEnabled) {{
        return matureEnabled ? ALL_SET : VALID_SET;
    }}

    function isValidAction(actionName, matureEnabled) {{
        if (!actionName || typeof actionName !== 'string') return false;
        const a = actionName.trim().toLowerCase();
        return matureEnabled ? ALL_SET.has(a) : VALID_SET.has(a);
    }}

    function getActionSpec(actionName) {{
        if (!actionName || typeof actionName !== 'string') return null;
        return ACTION_SPECS[actionName.trim().toLowerCase()] || null;
    }}

    function costOf(actionName) {{
        const spec = getActionSpec(actionName);
        return spec ? spec.cost_key : null;
    }}

    function bracketOrder() {{
        return [...BRACKET_ORDER];
    }}

    function actionsForScope(scopeName) {{
        if (!scopeName) return [];
        const target = scopeName.toLowerCase().trim();
        const seen = new Set();
        const out = [];
        for (const spec of Object.values(ACTION_SPECS)) {{
            if (seen.has(spec.id)) continue;
            seen.add(spec.id);
            const scopes = (spec.scope || '').toLowerCase().split(',').map(s => s.trim());
            if (scopes.includes(target)) {{
                out.push(spec);
            }}
        }}
        return out;
    }}

    const Actions = {{
        VALID_ACTIONS,
        MATURE_ACTIONS,
        ALL_ACTIONS,
        BRACKET_ORDER,
        ACTION_SPECS,
        VALID_SET,
        MATURE_SET,
        ALL_SET,
        allActions,
        isValidAction,
        getActionSpec,
        costOf,
        bracketOrder,
        actionsForScope
    }};

    if (typeof window !== 'undefined') {{
        window.Actions = Actions;
    }}
    if (typeof module !== 'undefined' && module.exports) {{
        module.exports = Actions;
    }}
}})();
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write generated file")
    parser.add_argument("--check", action="store_true", help="fail on drift")
    args = parser.parse_args()

    content = build_js()

    if args.write:
        OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUT_PATH.write_text(content, encoding="utf-8")
        print(f"Wrote {OUT_PATH.relative_to(ROOT)} ({len(content)} bytes)")
        return 0

    if args.check:
        if not OUT_PATH.exists():
            sys.stderr.write(f"FAIL: {OUT_PATH.relative_to(ROOT)} does not exist. Run with --write.\n")
            return 1
        existing = OUT_PATH.read_text(encoding="utf-8")
        if existing.replace("\r\n", "\n") != content.replace("\r\n", "\n"):
            sys.stderr.write(f"FAIL: {OUT_PATH.relative_to(ROOT)} is out of sync with engine/actions.py. Run tools/actions_index.py --write.\n")
            return 1
        print("OK: actions.generated.js is up to date.")
        return 0

    parser.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
